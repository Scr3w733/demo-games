export function translate(locale: LocaleId, key: string, values: Record<string, string | number> = {}): string {
  const table = locale === 'en' ? EN : RU;
  let text = table[key] ?? RU[key] ?? key;
  for (const [name, value] of Object.entries(values)) text = text.replace(`{${name}}`, String(value));
  return text;
}
